import assert from "node:assert/strict"
import path from "node:path"
import { comNavegador } from "./browser-harness.mjs"

await comNavegador(async ({ command, avaliar, esperar, clicar, carregarArquivo, origem, falhasJs }) => {
  const pagina = async rota => command("Page.navigate", { url: origem + rota })
  const botao = texto => `[...document.querySelectorAll("button")].find(e=>e.textContent.includes(${JSON.stringify(texto)}))`
  async function preencher(label, valor) {
    await avaliar(`(()=>{const root=document.querySelector('[role=dialog]')||document;const label=[...root.querySelectorAll('label')].find(e=>e.textContent.startsWith(${JSON.stringify(label)})&&e.querySelector('input,textarea'));const e=label?.querySelector('input,textarea');if(!e)throw Error('Campo não encontrado');const proto=e.tagName==='TEXTAREA'?HTMLTextAreaElement.prototype:HTMLInputElement.prototype;Object.getOwnPropertyDescriptor(proto,'value').set.call(e,${JSON.stringify(valor)});e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new Event('change',{bubbles:true}));})()`)
  }
  async function escolher(label, opcao) {
    await clicar(`document.getElementById([...(document.querySelector('[role=dialog]')||document).querySelectorAll('label')].find(e=>e.textContent===${JSON.stringify(label)}).htmlFor)`)
    await esperar('document.querySelectorAll("[role=option]").length > 0')
    await clicar(`[...document.querySelectorAll('[role=option]')].find(e=>e.textContent===${JSON.stringify(opcao)})`)
  }
  const cadastros = () => avaliar('JSON.parse(localStorage.getItem("sobera:gestao:v1:exemplo"))')
  await pagina("/portal-atencao-basica/administracao/usuarios")
  await esperar('document.body.innerText.includes("Gestão de usuários")')
  assert.ok(await avaliar('!!document.querySelector("section[aria-label=\\"Administração\\"] a[href=\\"/portal-atencao-basica/administracao/dados\\"]")'))
  assert.ok(await avaliar('!!document.querySelector("section[aria-label=\\"Gestão da APS\\"] a[href=\\"/portal-atencao-basica/plano-acao\\"]")'))
  await clicar('document.querySelector(\'button[aria-label="Abrir menu do usuário"]\')')
  await esperar('!!document.querySelector("[role=menu]")')
  await clicar('[...document.querySelectorAll("[role=menuitem]")].find(e=>e.textContent.includes("Meu perfil"))')
  await esperar('!!document.querySelector("[role=dialog]")')
  await preencher("Seu nome", "Marina Oliveira")
  await preencher("Seu e-mail", "marina@example.com")
  await clicar(botao("Salvar perfil"))
  await esperar('!document.querySelector("[role=dialog]") && document.querySelector(\'button[title="Marina Oliveira"]\')')
  await pagina("/portal-atencao-basica/administracao/usuarios")
  await esperar('!!document.querySelector(\'button[title="Marina Oliveira"]\') && document.body.innerText.includes("Cadastre o primeiro usuário")')
  assert.equal((await avaliar('JSON.parse(localStorage.getItem("sobera:perfil:v1"))')).email, "marina@example.com")
  console.log("Navegador: perfil no topbar, edição e persistência sem criar usuário administrativo OK.")
  await clicar(botao("Novo usuário"))
  await esperar('!!document.querySelector("[role=dialog]")')
  await preencher("Nome completo", "Ana Gestora")
  await preencher("E-mail", "ana@example.com")
  await clicar(botao("Salvar usuário"))
  await esperar('!document.querySelector("[role=dialog]") && document.body.innerText.includes("Ana Gestora")')
  const usuarioId = (await cadastros()).usuarios[0].id
  await clicar(botao("Novo usuário"))
  await preencher("Nome completo", "Cadastro duplicado")
  await preencher("E-mail", "ANA@example.com")
  await clicar(botao("Salvar usuário"))
  await esperar('document.body.innerText.includes("Este e-mail já está cadastrado")')
  await clicar(botao("Cancelar"))
  assert.equal((await cadastros()).usuarios.length, 1)
  console.log("Navegador: agrupamento do menu, cadastro de usuário e bloqueio de e-mail duplicado OK.")

  await pagina("/portal-atencao-basica/dashboard")
  await esperar('document.body.innerText.includes("Prioridades para a gestão")')
  assert.ok(await avaliar('document.body.innerText.includes("Mais acesso (C1) por equipe") && document.body.innerText.includes("Insights da APS")'))
  assert.ok(await avaliar('!document.querySelector("header").textContent.includes("Dados de exemplo")'))
  await clicar('document.querySelector(\'button[aria-label="Ajuda sobre Competência"]\')')
  await esperar('document.querySelector("[role=dialog]")?.innerText.includes("Mês de referência dos atendimentos")')
  await clicar(botao("Fechar"))
  await esperar('!document.querySelector("[role=dialog]")')
  const controleInsights = '[...document.querySelectorAll("summary")].find(e=>e.textContent.includes("Insights da APS"))'
  assert.ok(await avaliar(`!(${controleInsights}).parentElement.open && !document.body.innerText.includes("Sugestão 1 de 6")`))
  await clicar(controleInsights)
  await esperar('document.body.innerText.includes("Sugestão 1 de 6")')
  await clicar('document.querySelector(\'button[aria-label="Próxima sugestão"]\')')
  await esperar('document.body.innerText.includes("Sugestão 2 de 6")')
  await clicar(controleInsights)
  await esperar('!document.body.innerText.includes("Sugestão 2 de 6")')
  await clicar(controleInsights)
  await esperar('document.body.innerText.includes("Sugestão 2 de 6")')
  await clicar('document.querySelector(\'button[aria-label="Sugestão anterior"]\')')
  await clicar('[...document.querySelectorAll("a")].find(e=>e.textContent==="Gerar plano de ação")')
  await esperar('!!document.querySelector("[role=dialog]")')
  assert.ok(await avaliar('document.querySelector("textarea").value.includes("Conferir o arquivo")'))
  assert.equal((await cadastros()).acoes.length, 0)
  await clicar(botao("Cancelar"))
  await pagina("/portal-atencao-basica/dashboard")
  await esperar('document.body.innerText.includes("Prioridades para a gestão")')
  await clicar('document.querySelector(\'a[href="/portal-atencao-basica/plano-acao?nova=1&equipe=centro-2"]\')')
  await esperar('!!document.querySelector("[role=dialog]")')
  await preencher("Intervenção planejada", "Reorganizar a agenda programada com a equipe e revisar o acolhimento.")
  await escolher("Responsável *", "Ana Gestora")
  await preencher("Prazo", "2020-01-01")
  await preencher("Observação de acompanhamento", "Intervenção pactuada com a coordenação.")
  await clicar(botao("Salvar ação"))
  await esperar('!document.querySelector("[role=dialog]") && document.body.innerText.includes("Em atraso")')
  let dados = await cadastros()
  assert.equal(dados.acoes.length, 1)
  assert.equal(dados.acoes[0].responsavelId, usuarioId)
  assert.equal(dados.acoes[0].equipeId, "centro-2")
  const id = dados.acoes[0].id
  const baseline = dados.acoes[0].valorInicial
  await pagina("/portal-atencao-basica/dashboard")
  await esperar('document.body.innerText.includes("Acompanhar ação")')
  await clicar(`document.querySelector('a[href="/portal-atencao-basica/plano-acao?acao=${id}"]')`)
  await esperar('document.body.innerText.includes("Atualizar ação")')
  await escolher("Status", "Em andamento")
  await preencher("Observação de acompanhamento", "Agenda revisada em reunião de equipe.")
  await clicar(botao("Salvar ação"))
  await esperar('!document.querySelector("[role=dialog]")')
  dados = await cadastros()
  assert.equal(dados.acoes.length, 1)
  assert.equal(dados.acoes[0].status, "Em andamento")
  assert.equal(dados.acoes[0].historico.length, 2)
  console.log("Navegador: ação vinculada à prioridade, responsável, atraso e acompanhamento sem duplicação OK.")

  await clicar(botao("Atualizar / detalhes"))
  await escolher("Status", "Concluída")
  await preencher("Resultado e avaliação", "Intervenção executada; manter monitoramento para avaliar os próximos resultados.")
  await clicar(botao("Salvar ação"))
  await esperar('!document.querySelector("[role=dialog]")')
  dados = await cadastros()
  assert.equal(dados.acoes[0].status, "Concluída")
  assert.equal(dados.acoes[0].valorInicial, baseline)
  assert.ok(dados.acoes[0].revisao.observacao.includes("Intervenção executada"))
  await pagina("/portal-atencao-basica/plano-acao")
  await esperar('document.body.innerText.includes("Intervenção executada")')
  await escolher("Status", "Pendente")
  await esperar('document.body.innerText.includes("0 ações encontradas")')
  await escolher("Status", "Concluída")
  await esperar('document.body.innerText.includes("1 ação encontrada")')
  console.log("Navegador: conclusão com revisão, preservação da origem, filtros e recarregamento OK.")

  await pagina("/portal-atencao-basica/administracao/usuarios")
  await esperar('document.body.innerText.includes("Ana Gestora")')
  await clicar('document.querySelector(\'button[aria-label="Editar Ana Gestora"]\')')
  await preencher("Nome completo", "Ana Coordenadora")
  await escolher("Perfil", "Administrador")
  await clicar(botao("Salvar usuário"))
  await esperar('!document.querySelector("[role=dialog]") && document.body.innerText.includes("Ana Coordenadora")')
  await clicar('document.querySelector(\'button[aria-label="Inativar Ana Coordenadora"]\')')
  await esperar('document.body.innerText.includes("Usuário inativado")')
  assert.equal((await cadastros()).usuarios[0].ativo, false)
  await pagina("/portal-atencao-basica/plano-acao")
  await esperar('document.body.innerText.includes("Ana Coordenadora") && document.body.innerText.includes("(inativo)")')
  assert.equal((await cadastros()).acoes.length, 1)
  console.log("Navegador: edição e inativação de usuário preservam o histórico das ações.")

  await pagina("/portal-atencao-basica/dados")
  await esperar('!!document.querySelector("input[type=file]")')
  assert.ok(await avaliar('location.pathname.endsWith("/administracao/dados")'))
  await carregarArquivo(path.resolve("public/exemplos/c1-modelo.csv"))
  await esperar('document.body.innerText.includes("Prévia dos primeiros 10 registros")')
  await clicar('document.querySelector("input[type=checkbox]")')
  await clicar(botao("Substituir base e atualizar"))
  await esperar('document.body.innerText.includes("Base importada e salva")')
  await pagina("/portal-atencao-basica/administracao/usuarios")
  await esperar('document.body.innerText.includes("Cadastre o primeiro usuário")')
  assert.ok(await avaliar('!document.body.innerText.includes("Ana Coordenadora")'))
  assert.equal((await cadastros()).acoes.length, 1)
  await pagina("/portal-atencao-basica/administracao/dados")
  await esperar('document.body.innerText.includes("Usar base de exemplo")')
  await clicar(botao("Usar base de exemplo"))
  await esperar('!!document.querySelector("[role=alertdialog]")')
  await clicar(botao("Usar exemplo"))
  await esperar('document.body.innerText.includes("Armação dos Búzios, RJ")')
  await pagina("/portal-atencao-basica/administracao/usuarios")
  await esperar('document.body.innerText.includes("Ana Coordenadora")')
  assert.deepEqual(falhasJs, [])
  console.log("Navegador: isolamento entre municípios, retorno à base anterior e rota legada OK; sem exceções JavaScript.")
})
